import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";
import { parse as parseYaml } from "yaml";
import { z } from "zod";

// Product docs live as Markdown in product-docs/; the app's /docs page, the
// agents' product_help and the /docs workspace mount all read this module.
const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const docsRoot = join(appRoot, "product-docs");

const outputPath = join(appRoot, "src/convex/productDocs/generated.ts");

const checkOnly = process.argv.includes("--check");

// Generated from the settings registry at runtime, not from a Markdown file.
const GENERATED_SLUGS = new Set(["configuracoes"]);

const fail = (message) => {
  throw new Error(`product docs: ${message}`);
};

const toPosix = (path) => path.split(sep).join("/");

const FrontmatterSchema = z.object({
  title: z.string().trim().min(1).max(80),
  description: z.string().trim().min(1).max(300),
  order: z.number().int(),
  keywords: z.string().default(""),
});

const errorMessage = (error) => z.instanceof(Error).safeParse(error).data?.message ?? String(error);

function parsePage(raw, sourcePath) {
  const normalized = raw.replace(/\r\n/g, "\n").replace(/\r/g, "\n");
  const match = normalized.match(/^---\n([\s\S]*?)\n---(?:\n|$)/);

  if (!match) fail(`${sourcePath} must start with YAML frontmatter enclosed by --- lines`);

  let rawFrontmatter;

  try {
    rawFrontmatter = parseYaml(match[1]);
  } catch (error) {
    fail(`${sourcePath} has invalid YAML: ${errorMessage(error)}`);
  }

  const parsed = FrontmatterSchema.safeParse(rawFrontmatter);

  if (!parsed.success) fail(`${sourcePath} has invalid frontmatter: ${parsed.error.message}`);

  return { ...parsed.data, markdown: normalized.slice(match[0].length).trim() };
}

const entries = await readdir(docsRoot, { withFileTypes: true });

const pages = [];

for (const entry of entries.toSorted((a, b) => a.name.localeCompare(b.name))) {
  if (!entry.isFile() || !entry.name.endsWith(".md") || entry.name === "README.md") continue;
  const slug = entry.name.slice(0, -".md".length);

  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) fail(`${entry.name} must be a kebab-case name`);

  if (GENERATED_SLUGS.has(slug)) fail(`${entry.name} is generated from the settings registry`);
  const sourcePath = toPosix(relative(appRoot, join(docsRoot, entry.name)));

  pages.push({
    slug,
    ...parsePage(await readFile(join(docsRoot, entry.name), "utf8"), sourcePath),
  });
}

const known = new Set([...pages.map((page) => page.slug), ...GENERATED_SLUGS]);

for (const page of pages) {
  for (const [, target] of page.markdown.matchAll(/\]\(\/docs\/([a-z0-9-]+)\)/g)) {
    if (!known.has(target)) fail(`${page.slug}.md links to /docs/${target}, which does not exist`);
  }
}

pages.sort((left, right) => left.order - right.order || left.slug.localeCompare(right.slug));

const generated = `// Generated by scripts/build-product-docs.mjs from product-docs/. Do not edit by hand.\nimport type { ProductDocSource } from "./types";\n\nexport const PRODUCT_DOC_SOURCES = ${JSON.stringify(pages, null, 2)} satisfies readonly ProductDocSource[];\n`;

const formatted = await format(outputPath, generated);

if (formatted.errors.length > 0) fail("could not format generated docs");

const output = formatted.code;

if (checkOnly) {
  let current = "";

  try {
    current = await readFile(outputPath, "utf8");
  } catch {}

  if (current !== output) fail("generated docs are stale; run pnpm docs:build");
} else {
  await writeFile(outputPath, output);
  console.log(`Generated ${pages.length} doc page(s) in ${toPosix(relative(appRoot, outputPath))}`);
}
